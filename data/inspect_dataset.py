"""
Inspects a downloaded dataset file and writes a factual report — no
assumptions about schema, just what's actually in the file. Run this
the moment the real Kaggle dataset is downloaded, before touching
anything else, per the project brief's "inspect before coding" rule.

Usage:
    python3 inspect_dataset.py path/to/listings.csv
    python3 inspect_dataset.py path/to/listings.csv path/to/reviews.csv

Output:
    Prints a report to stdout AND writes it to
    data/INSPECTION_REPORT.md, which should then be used to update
    data/DATA_DICTIONARY.md by hand (the actual documentation is
    written by a person reading this report, not auto-generated,
    since judgement calls like "is this a duplicate" need a human).
"""
import sys
import os
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))


def inspect_file(path: str) -> str:
    lines = [f"## {os.path.basename(path)}", ""]

    if not os.path.exists(path):
        lines.append(f"**FILE NOT FOUND: {path}**")
        return "\n".join(lines)

    size_mb = os.path.getsize(path) / (1024 * 1024)
    lines.append(f"- File size: {size_mb:.2f} MB")

    try:
        df = pd.read_csv(path, low_memory=False)
    except Exception as e:
        lines.append(f"- **Failed to read as CSV: {e}**")
        return "\n".join(lines)

    lines.append(f"- Rows: {len(df)}")
    lines.append(f"- Columns: {len(df.columns)}")
    lines.append("")
    lines.append("### Columns, dtypes, missing %")
    lines.append("")
    lines.append("| Column | Dtype | Missing | Missing % | Unique values |")
    lines.append("|---|---|---|---|---|")
    for col in df.columns:
        missing = df[col].isna().sum()
        missing_pct = round(missing / len(df) * 100, 2) if len(df) else 0
        nunique = df[col].nunique(dropna=True)
        lines.append(f"| {col} | {df[col].dtype} | {missing} | {missing_pct}% | {nunique} |")

    lines.append("")
    dup_count = df.duplicated().sum()
    lines.append(f"### Duplicates: {dup_count} fully duplicate rows")

    # If there's an obvious ID column, also check duplicates on it specifically.
    id_candidates = [c for c in df.columns if "id" in c.lower() and df[c].nunique() > 1]
    for id_col in id_candidates[:3]:
        dup_on_id = df[id_col].duplicated().sum()
        lines.append(f"- Duplicate `{id_col}` values: {dup_on_id}")

    lines.append("")
    numeric_cols = df.select_dtypes(include="number").columns.tolist()
    if numeric_cols:
        lines.append("### Numeric column ranges")
        lines.append("")
        lines.append("| Column | Min | Max | Mean | Median |")
        lines.append("|---|---|---|---|---|")
        for col in numeric_cols:
            lines.append(
                f"| {col} | {df[col].min()} | {df[col].max()} | "
                f"{round(df[col].mean(), 2)} | {round(df[col].median(), 2)} |"
            )

    lines.append("")
    categorical_cols = df.select_dtypes(include="object").columns.tolist()
    if categorical_cols:
        lines.append("### Categorical column sample values (top 5 by frequency)")
        lines.append("")
        for col in categorical_cols[:15]:  # cap output for very wide files
            top = df[col].value_counts(dropna=True).head(5)
            sample = ", ".join(f"{v} ({c})" for v, c in top.items())
            lines.append(f"- **{col}**: {sample}")

    return "\n".join(lines)


def main():
    if len(sys.argv) < 2:
        print("Usage: python3 inspect_dataset.py path/to/file.csv [path/to/other.csv ...]")
        sys.exit(1)

    report_sections = [
        "# Dataset Inspection Report",
        "",
        "Generated by `data/inspect_dataset.py`. This is a factual report of what's",
        "actually in the file(s) below — use it to update `data/DATA_DICTIONARY.md`",
        "by hand, and to note any differences from what was previously documented.",
        "",
    ]
    for path in sys.argv[1:]:
        report_sections.append(inspect_file(path))
        report_sections.append("")

    report = "\n".join(report_sections)
    print(report)

    out_path = os.path.join(HERE, "INSPECTION_REPORT.md")
    with open(out_path, "w") as f:
        f.write(report)
    print(f"\nReport also written to {out_path}")


if __name__ == "__main__":
    main()
